const {chromium}=require('C:/Users/Administrator/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const fs=require('node:fs');
(async()=>{
  const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const context=await browser.newContext({viewport:{width:1280,height:800}});
  const external=[],errors=[],failed=[];
  await context.route('**/*',route=>{const url=route.request().url();if(/^https?:/.test(url)&&!url.startsWith('http://localhost:3210/')){external.push(url);return route.abort();}return route.continue();});
  const page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message));
  page.on('response',r=>{if(r.status()>=400)failed.push(r.status()+' '+r.url());});
  fs.mkdirSync('.tmp-ghasaq-qa',{recursive:true});
  await page.goto('http://localhost:3210/games/ghasaq/',{waitUntil:'networkidle'});
  await page.waitForFunction(()=>document.body.dataset.screen==='splash',{timeout:60000});
  await page.evaluate(()=>document.fonts.load('600 20px "Noto Sans SC Local"','黄昏守城'));
  await page.locator('#splash').click();
  await page.waitForFunction(()=>document.body.dataset.screen==='main');
  await page.waitForTimeout(1000);
  await page.locator('#main').screenshot({path:'.tmp-ghasaq-qa/main.png',animations:'disabled'});
  const ui=await page.evaluate(()=>({lang:document.documentElement.lang,dir:document.documentElement.dir,font:document.fonts.check('600 20px "Noto Sans SC Local"','黄昏守城'),text:document.body.innerText}));
  if(ui.lang!=='zh-CN'||ui.dir!=='ltr'||!ui.font||!ui.text.includes('开始行动')||/[\u0600-\u06ff]/.test(ui.text))throw Error('Chinese UI/font check failed');
  await page.locator('[data-act="settings"]').click();
  await page.waitForFunction(()=>document.body.dataset.screen==='settings');
  await page.waitForTimeout(700);
  await page.locator('#settings').screenshot({path:'.tmp-ghasaq-qa/settings.png',animations:'disabled'});
  await page.locator('#setBack').click();
  await page.locator('[data-act="play"]').click();
  await page.waitForFunction(()=>document.body.dataset.screen==='brief');
  await page.waitForFunction(()=>!document.querySelector('#briefStart').classList.contains('busy'));
  await page.waitForTimeout(700);
  await page.locator('#brief').screenshot({path:'.tmp-ghasaq-qa/brief.png',animations:'disabled'});
  await page.locator('#briefStart').click();
  await page.waitForFunction(()=>document.querySelector('#hud').hidden===false&&document.body.dataset.screen==='',{timeout:30000});
  await page.waitForTimeout(1000);
  await page.screenshot({path:'.tmp-ghasaq-qa/playing.png'});
  await page.keyboard.press('KeyP');
  await page.waitForFunction(()=>document.body.dataset.screen==='pause');
  const mobile=await context.newPage();
  mobile.on('pageerror',e=>errors.push('mobile: '+e.message));
  await mobile.setViewportSize({width:844,height:390});
  await mobile.goto('http://localhost:3210/games/ghasaq/#touch-autotest-combat',{waitUntil:'networkidle'});
  await mobile.waitForFunction(()=>document.querySelector('#hud').hidden===false,{timeout:60000});
  await mobile.screenshot({path:'.tmp-ghasaq-qa/mobile.png'});
  await page.goto('http://localhost:3210/');
  const launcher=page.locator('#open-ghasaq');
  if(await launcher.getAttribute('href')!=='/games/ghasaq/')throw Error('Missing local launcher');
  await browser.close();
  const result={ui:{lang:ui.lang,dir:ui.dir,fontLoaded:ui.font},externalRequests:external,pageErrors:errors,failedResponses:failed,desktopStartAndPause:true,mobileCombatLoaded:true};
  fs.writeFileSync('.tmp-ghasaq-qa/result.json',JSON.stringify(result,null,2));
  console.log(JSON.stringify(result));
  if(external.length||errors.length||failed.length)process.exitCode=1;
})().catch(e=>{console.error(e);process.exit(1)});
